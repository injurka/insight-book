import { describe, expect, it } from 'bun:test'
import { parseHtmlBuffer } from './html.service'
import { parseSubtitleBuffer } from './subtitle.service'

describe('subtitle.service — parseSubtitleBuffer', () => {
  it('parses .srt timestamps, multi-line cues, strips HTML tags, and detects Russian language', () => {
    const srtContent = [
      '1',
      '00:00:01,200 --> 00:00:04,500',
      '<i>Привет, мир!</i>',
      'Как поживаешь сегодня?',
      '',
      '2',
      '00:00:05,000 --> 00:00:07,000',
      '♪ ♪',
      '',
      '3',
      '00:00:08,100 --> 00:00:11,900',
      '<b>Отлично</b>, мы читаем субтитры как книгу.',
    ].join('\r\n')

    const bytes = new TextEncoder().encode(srtContent)
    const parsed = parseSubtitleBuffer(bytes, 'movie-episode-01.srt')

    expect(parsed.title).toBe('movie-episode-01')
    expect(parsed.author).toBeNull()
    expect(parsed.language).toBe('ru')
    expect(parsed.toc).toHaveLength(0)
    expect(parsed.pages).toHaveLength(1)
    expect(parsed.pages[0]).toContain('<p>Привет, мир! Как поживаешь сегодня?</p>')
    expect(parsed.pages[0]).toContain('<p>Отлично, мы читаем субтитры как книгу.</p>')
    expect(parsed.pages[0]).not.toContain('<i>')
    expect(parsed.pages[0]).not.toContain('♪')
  })

  it('parses .vtt with metadata, skips NOTE/STYLE blocks, extracts <v Speaker>, deduplicates rollout cues, and builds 10-min TOC', () => {
    const vttContent = [
      'WEBVTT',
      'Title: Quantum Lecture',
      'Language: en-US',
      '',
      'STYLE',
      '::cue { color: yellow; }',
      '',
      'NOTE This is a comment block that must be ignored',
      '',
      '00:00:02.000 --> 00:00:05.000 align:start position:0%',
      '<v Alice>Welcome to the <c.yellow>quantum</c> mechanics lecture.</v>',
      '',
      '00:00:05.000 --> 00:00:08.000',
      'Welcome to the quantum mechanics lecture.',
      'Today we explore wave functions.',
      '',
      '00:00:08.000 --> 00:00:10.000',
      'Today we explore wave functions.',
      '',
      '00:12:30.000 --> 00:12:35.000',
      '<v.loud Bob>Do we need linear algebra for this part?</v>',
    ].join('\n')

    const bytes = new TextEncoder().encode(vttContent)
    const parsed = parseSubtitleBuffer(bytes, 'lecture.vtt')

    expect(parsed.title).toBe('Quantum Lecture')
    expect(parsed.language).toBe('en')
    expect(parsed.toc).toHaveLength(2)
    expect(parsed.toc[0].title).toBe('00:00 — 10:00')
    expect(parsed.toc[1].title).toBe('10:00 — 20:00')

    const html = parsed.pages.join('\n')
    expect(html).toContain('<h2>00:00 — 10:00</h2>')
    expect(html).toContain('<h2>10:00 — 20:00</h2>')
    expect(html).toContain('<p><strong>Alice:</strong> Welcome to the quantum mechanics lecture.</p>')
    expect(html).toContain('<p>Today we explore wave functions.</p>')
    expect(html).toContain('<p><strong>Bob:</strong> Do we need linear algebra for this part?</p>')
    expect(html).not.toContain('comment block')
    expect(html).not.toContain('::cue')

    // Ensure "Today we explore wave functions." only appears once due to deduplication
    const matches = html.match(/Today we explore wave functions\./g) || []
    expect(matches).toHaveLength(1)
  })

  it('parses .ass script info and events, strips override tags, ignores drawing commands, and handles \\N and speakers', () => {
    const assContent = [
      '[Script Info]',
      '; Script generated by Aegisub',
      'Title: Anime Episode 5',
      'ScriptType: v4.00+',
      '',
      '[Events]',
      'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
      'Dialogue: 0,0:00:01.00,0:00:03.50,Default,Sakura,0,0,0,,{\\pos(320,240)\\fad(100,100)}Доброе утро,\\Nвсем присутствующим!',
      'Dialogue: 0,0:00:04.00,0:00:06.00,Default,Default,0,0,0,,{\\p1}m 0 0 l 100 0 100 100 0 100{\\p0}',
      'Dialogue: 0,0:00:07.00,0:00:10.00,Default,Default,0,0,0,,{\\i1}Идите сюда,\\hбыстрее, друзья!{\\i0}',
    ].join('\n')

    const bytes = new TextEncoder().encode(assContent)
    const parsed = parseSubtitleBuffer(bytes, 'ep05.ass')

    expect(parsed.title).toBe('Anime Episode 5')
    expect(parsed.language).toBe('ru')

    const html = parsed.pages.join('\n')
    expect(html).toContain('<p><strong>Sakura:</strong> Доброе утро, всем присутствующим!</p>')
    expect(html).toContain('<p>Идите сюда, быстрее, друзья!</p>')
    expect(html).not.toContain('\\pos')
    expect(html).not.toContain('m 0 0 l 100')
    expect(html).not.toContain('<strong>Default:</strong>')
  })
})

describe('html.service — parseHtmlBuffer', () => {
  it('decodes Windows-1251 via <meta charset="windows-1251"> and extracts Russian content cleanly', () => {
    // Encode Windows-1251 bytes manually for:
    // <html><head><meta charset="windows-1251"><title>Русская классика</title></head><body><h1>Глава первая</h1><p>Мой дядя самых честных правил.</p></body></html>
    const unicodeToCp1251 = (str: string): Uint8Array => {
      const out: number[] = []

      for (let i = 0; i < str.length; i++) {
        const code = str.charCodeAt(i)

        if (code < 0x80) {
          out.push(code)
        }
        else if (code >= 0x0410 && code <= 0x044F) {
          out.push(code - 0x0410 + 0xC0)
        }
        else if (code === 0x0401) {
          out.push(0xA8)
        }
        else if (code === 0x0451) {
          out.push(0xB8)
        }
        else {
          out.push(0x3F)
        }
      }

      return new Uint8Array(out)
    }

    const rawHtml = '<html><head><meta charset="windows-1251"><title>Русская классика</title></head><body><h1>Глава первая</h1><p>Мой дядя самых честных правил, когда не в шутку занемог.</p></body></html>'
    const cp1251Bytes = unicodeToCp1251(rawHtml)

    const parsed = parseHtmlBuffer(cp1251Bytes, 'onegin.html')

    expect(parsed.title).toBe('Русская классика')
    expect(parsed.language).toBe('ru')
    expect(parsed.toc).toHaveLength(1)
    expect(parsed.toc[0].title).toBe('Глава первая')
    expect(parsed.toc[0].level).toBe(1)
    expect(parsed.pages[0]).toContain('<h1>Глава первая</h1>')
    expect(parsed.pages[0]).toContain('<p>Мой дядя самых честных правил, когда не в шутку занемог.</p>')
  })

  it('extracts metadata, removes <script>/<nav>/<aside>, builds TOC from headings, and strips dangerous attributes', () => {
    const htmlContent = `
      <!DOCTYPE html>
      <html lang="en">
        <head>
          <title>Fallback Title</title>
          <meta property="og:title" content="Clean Architecture Guide" />
          <meta name="author" content="Robert Martin" />
          <style>body { color: red; }</style>
          <script>alert("xss")</script>
        </head>
        <body>
          <nav><a href="/home">Home Navigation</a></nav>
          <aside>Sidebar advertisement</aside>
          <main>
            <h1 class="hero" onclick="evil()">Chapter 1: Introduction</h1>
            <p style="color:blue" onmouseover="hack()">Software architecture is the art of drawing lines that <strong class="bold">matter</strong>.</p>
            <div class="wrapper">
              Direct text inside a div container.
              <h2>Section 1.1: Boundaries</h2>
              <ul>
                <li onclick="bad()">First principle</li>
                <li>Second principle</li>
              </ul>
            </div>
            <img src="javascript:alert(1)" onerror="steal()" />
            <img src="https://example.com/diagram.png" alt="Architecture Diagram" onerror="steal()" />
          </main>
          <footer>Copyright 2026</footer>
        </body>
      </html>
    `

    const bytes = new TextEncoder().encode(htmlContent)
    const parsed = parseHtmlBuffer(bytes, 'arch.html')

    expect(parsed.title).toBe('Clean Architecture Guide')
    expect(parsed.author).toBe('Robert Martin')
    expect(parsed.language).toBe('en')

    expect(parsed.toc).toHaveLength(2)
    expect(parsed.toc[0]).toMatchObject({
      title: 'Chapter 1: Introduction',
      level: 1,
      pageNum: 1,
    })
    expect(parsed.toc[1]).toMatchObject({
      title: 'Section 1.1: Boundaries',
      level: 2,
      pageNum: 1,
    })

    const combinedHtml = parsed.pages.join('\n')
    expect(combinedHtml).toContain('<h1>Chapter 1: Introduction</h1>')
    expect(combinedHtml).toContain('<p>Software architecture is the art of drawing lines that <strong>matter</strong>.</p>')
    expect(combinedHtml).toContain('<p>Direct text inside a div container.</p>')
    expect(combinedHtml).toContain('<h2>Section 1.1: Boundaries</h2>')
    expect(combinedHtml).toContain('<ul><li>First principle</li><li>Second principle</li></ul>')
    expect(combinedHtml).toContain('<img src="https://example.com/diagram.png" alt="Architecture Diagram" />')

    // Ensure noise and dangerous attributes are completely stripped
    expect(combinedHtml).not.toContain('Home Navigation')
    expect(combinedHtml).not.toContain('Sidebar advertisement')
    expect(combinedHtml).not.toContain('Copyright 2026')
    expect(combinedHtml).not.toContain('alert("xss")')
    expect(combinedHtml).not.toContain('onclick')
    expect(combinedHtml).not.toContain('onmouseover')
    expect(combinedHtml).not.toContain('onerror')
    expect(combinedHtml).not.toContain('javascript:alert')
    expect(combinedHtml).not.toContain('style=')
    expect(combinedHtml).not.toContain('class=')
  })
})
