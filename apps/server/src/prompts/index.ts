export function getLangName(code: string): string {
  const map: Record<string, string> = {
    zh: 'китайского',
    ja: 'японского',
    en: 'английского',
    ko: 'корейского',
    fr: 'французского',
    de: 'немецкого',
    es: 'испанского',
  }
  return map[code.toLowerCase()] || 'иностранного'
}

